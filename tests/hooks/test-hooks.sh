# --- helpers -------------------------------------------------------------------
run() {  # run <event> <json>  -> sets rc, out, err
    out="$(printf '%s' "$2" | "$shell" "$hook" "$1" 2>"$work/stderr")"
    rc=$?
    err="$(cat "$work/stderr")"
}

check() {  # check <name> <condition...>
    name="$1"; shift
    if "$@"; then
        passed=$((passed + 1))
    else
        failed=$((failed + 1))
        printf 'FAIL %s\n  rc=%s\n  stdout=%s\n  stderr=%s\n' "$name" "$rc" "$out" "$err"
        # In CI also as an annotation, which the run page shows without the log.
        if [ "${GITHUB_ACTIONS:-}" = true ]; then
            printf '::error title=hook test failed (bash %s)::%s - rc=%s out=%.300s err=%.200s\n' \
                "$("$shell" -c 'echo $BASH_VERSION')" "$name" "$rc" "$out" "$err"
        fi
    fi
}

has() { case "$1" in *"$2"*) return 0 ;; esac; return 1; }
denied() { [ "$rc" -eq 0 ] && has "$out" '"permissionDecision":"deny"'; }
quiet() { [ "$rc" -eq 0 ] && [ -z "$out$err" ]; }
noted() { [ "$rc" -eq 0 ] && has "$out" '"additionalContext"'; }
valid_json() {
    for py in python3 python; do
        if command -v "$py" >/dev/null 2>&1 && "$py" -c 'print(1)' >/dev/null 2>&1; then
            "$py" -c 'import json,sys; json.loads(sys.argv[1])' "$out" 2>/dev/null
            return
        fi
    done
    return 0
}

edit_json() {  # edit_json <tool> <path> [session] [old] [new] [extra tool_input fields]  (old/new already JSON-escaped)
    printf '{"session_id":"%s","hook_event_name":"PreToolUse","tool_name":"%s","tool_input":{"file_path":"%s","old_string":"%s","new_string":"%s"%s}}' \
        "${3:-s1}" "$1" "$2" "${4:-a}" "${5:-b}" "${6:-}"
}

bash_json() {  # bash_json <command> <stdout> [session] [extra tool_input fields] [extra tool_response fields] [tool]
    printf '{"session_id":"%s","hook_event_name":"PostToolUse","tool_name":"%s","tool_input":{"command":"%s"%s},"tool_response":{"stdout":"%s","stderr":"","interrupted":false,"isImage":false%s}}' \
        "${3:-s1}" "${6:-Bash}" "$1" "${4:-}" "$2" "${5:-}"
}

failure_json() {  # failure_json <command> <error> [session] [tool]  - a command that exited non-zero
    printf '{"session_id":"%s","hook_event_name":"PostToolUseFailure","tool_name":"%s","tool_input":{"command":"%s"},"tool_use_id":"t1","error":"%s","is_interrupt":false}' \
        "${3:-s1}" "${4:-Bash}" "$1" "$2"
}

stop_json() {  # stop_json <active> [session]
    printf '{"session_id":"%s","hook_event_name":"Stop","stop_hook_active":%s}' "${2:-s1}" "$1"
}

