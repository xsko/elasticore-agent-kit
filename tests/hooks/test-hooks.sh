#!/usr/bin/env bash
# Feeds the plugin's hook script the JSON Claude Code sends and checks what it
# answers. Runs with the same tools the hook gets: bash and POSIX utilities, on
# Linux, macOS and Git Bash on Windows.
#
# usage: bash tests/hooks/test-hooks.sh        HOOK_BASH=/bin/bash picks the shell
# The fixtures go to a fresh directory under $TMPDIR, left for inspection.

set -u
here="$(cd "$(dirname "$0")" && pwd)"
hook="$here/../../plugins/elasticore/hooks/elasticore-hook.sh"
shell="${HOOK_BASH:-bash}"
work="$(mktemp -d "${TMPDIR:-/tmp}/elasticore-hook-test.XXXXXX")"
export CLAUDE_PLUGIN_DATA="$work/data"
unset ELASTICORE_ALLOW_GENERATED_EDITS ELASTICORE_ALLOW_FORCE

passed=0
failed=0

# --- fixtures: two projects, one on the rule engine and one without ----------------
engine="$work/engine"      # build.gradle with an elasticore { } block
legacy="$work/legacy"      # no block: the 2.x generator
for p in "$engine" "$legacy"; do
    mkdir -p "$p/src/main/java/com/acme/shop" "$p/src/main/resources/blueprint/shop/model" "$p/src/main/resources/i18n"
done
printf "plugins { id 'io.elasticore' version '3.0.0' }\n\nelasticore {\n    architecture = 'hexagonal'\n    language     = 'java'\n}\n" > "$engine/build.gradle"
printf "plugins { id 'io.elasticore' version '3.0.0' }\n" > "$legacy/build.gradle"

src="$engine/src/main/java/com/acme/shop"
blueprint="$engine/src/main/resources/blueprint"
i18n="$engine/src/main/resources/i18n"
printf '//ecd:-1375193215H20261020123214_V3.0\npackage com.acme.shop;\n\npublic class ProductDTO {}\n' > "$src/ProductDTO.java"
printf '//ecd:1883886029H20261020123214_V3.0\r\npackage com.acme.shop;\r\n\r\npublic class OrderDTO {}\r\n' > "$src/OrderDTO.java"
printf '\357\273\277//ecd:1H20261020123214_V3.0\npackage com.acme.shop;\n\npublic class BomDTO {}\n' > "$src/BomDTO.java"
printf '//ecd:1883886029H20261020123214_V3.0\n// Initially generated by ElastiCORE; no longer managed - do not remove this line.\npackage com.acme.shop;\n\npublic class ProductService {}\n' > "$src/ProductService.java"
printf '//ecd:1883886029H20261020123214_V3.0\n// Initially generated by ElastiCORE; no longer managed\342\200\224do not remove this line.\npackage com.acme.shop;\n\npublic class ProductController {}\n' > "$src/ProductController.java"
printf '//ecd:1883886029H20261020123214_V3.0\n// Initially generated by ElastiCORE; no longer managed.\npackage com.acme.shop;\n\nclass ProductServiceTest {}\n' > "$src/ProductServiceTest.java"
# A comment in MS949, not UTF-8, before the ownership line.
printf '//ecd:1883886029H20261020123214_V3.0\n// \307\321\261\333\n// Initially generated by ElastiCORE; no longer managed.\npackage com.acme.shop;\n\npublic class ProductMapper {}\n' > "$src/ProductMapper.java"
printf '//ecd:-901H20261020123214_V3.0\npackage com.acme.shop;\n\ninterface ProductRepository {\n// !-----------------------------------------------------------\n// ------------------------------------------------------------!\n}\n' > "$src/ProductRepository.java"
printf '//ecd:-902H20261020123214_V3.0\npackage com.acme.shop;\n\ninterface OrderRepository {\n    void touch();\n}\n' > "$src/OrderRepository.java"
printf 'package com.acme.shop;\n\npublic class ShopApplication {}\n' > "$src/ShopApplication.java"
printf '# Generated Schema File\n# Generated by ElastiCORE SchemaCodePublisher\n\nschema: {}\n' > "$blueprint/schema.yml"
printf '# ElastiCORE YAML DSL Guide\n\n## 1.\n' > "$blueprint/elasticore-dsl-guide.md"
printf '# Generated by ElastiCORE - the messages the shop API can answer with.\n# Regenerated with the model: do not edit.\nnot-found=Not found\n' > "$i18n/shop-messages.properties"
cp "$i18n/shop-messages.properties" "$i18n/shop-messages_ko.properties"
printf 'entity:\n  Product:\n    fields:\n      name: string(100)!\n' > "$blueprint/shop/model/entity.yml"
printf 'entity:\n  PurchaseOrder:\n    meta: entity @root @owner(customerId) @access(read=owner)\n    fields:\n      customerId: long\n' > "$blueprint/shop/model/order.yml"
cp "$blueprint/shop/model/order.yml" "$legacy/src/main/resources/blueprint/shop/model/order.yml"

managed="$src/ProductDTO.java"
model="$blueprint/shop/model/entity.yml"
rules="$blueprint/shop/model/order.yml"
legacy_rules="$legacy/src/main/resources/blueprint/shop/model/order.yml"

# --- helpers -------------------------------------------------------------------
run() {  # run <event> <json>  -> sets rc, out, err
    out="$(printf '%s' "$2" | "$shell" "$hook" "$1" 2>"$work/stderr")"
    rc=$?
    err="$(cat "$work/stderr")"
}

check() {  # check <name> <condition...>
    name="$1"; shift
    if "$@"; then
        passed=$((passed + 1))
    else
        failed=$((failed + 1))
        printf 'FAIL %s\n  rc=%s\n  stdout=%s\n  stderr=%s\n' "$name" "$rc" "$out" "$err"
        # In CI also as an annotation, which the run page shows without the log.
        if [ "${GITHUB_ACTIONS:-}" = true ]; then
            printf '::error title=hook test failed (bash %s)::%s - rc=%s out=%.300s err=%.200s\n' \
                "$("$shell" -c 'echo $BASH_VERSION')" "$name" "$rc" "$out" "$err"
        fi
    fi
}

has() { case "$1" in *"$2"*) return 0 ;; esac; return 1; }
denied() { [ "$rc" -eq 0 ] && has "$out" '"permissionDecision":"deny"'; }
quiet() { [ "$rc" -eq 0 ] && [ -z "$out$err" ]; }
noted() { [ "$rc" -eq 0 ] && has "$out" '"additionalContext"'; }
valid_json() {
    for py in python3 python; do
        if command -v "$py" >/dev/null 2>&1 && "$py" -c 'print(1)' >/dev/null 2>&1; then
            "$py" -c 'import json,sys; json.loads(sys.argv[1])' "$out" 2>/dev/null
            return
        fi
    done
    return 0
}

edit_json() {  # edit_json <tool> <path> [session] [old] [new]  (old/new already JSON-escaped)
    printf '{"session_id":"%s","hook_event_name":"PreToolUse","tool_name":"%s","tool_input":{"file_path":"%s","old_string":"%s","new_string":"%s"}}' \
        "${3:-s1}" "$1" "$2" "${4:-a}" "${5:-b}"
}

bash_json() {  # bash_json <command> <stdout> [session] [extra tool_input fields] [extra tool_response fields]
    printf '{"session_id":"%s","hook_event_name":"PostToolUse","tool_name":"Bash","tool_input":{"command":"%s"%s},"tool_response":{"stdout":"%s","stderr":"","interrupted":false,"isImage":false%s}}' \
        "${3:-s1}" "$1" "${4:-}" "$2" "${5:-}"
}

stop_json() {  # stop_json <active> [session]
    printf '{"session_id":"%s","hook_event_name":"Stop","stop_hook_active":%s}' "${2:-s1}" "$1"
}

marker="$CLAUDE_PLUGIN_DATA/dsl-changed-s1"
built3='> Task :elcore3\n=== elcore3: 1 written / 41 unchanged / 14 skipped / 0 failed ===\nBUILD SUCCESSFUL in 9s'
built2='> Task :elcore\nModelExtractor execution mode: default\nBUILD SUCCESSFUL in 7s'

# --- pre-edit: generated files are changed through the DSL ---------------------
run pre-edit "$(edit_json Edit "$managed")"
check "managed file is refused" denied
check "the refusal names the file, the DSL and the preserved block" eval 'has "$out" "$managed" && has "$out" "blueprint/<domain>" && has "$out" "preserved block"'
check "the refusal says not to go around it" eval 'has "$out" "Bash or a script"'
check "the refusal is valid JSON" valid_json

run pre-edit "$(edit_json Write "$managed")"
check "overwriting a managed file is refused" denied
run pre-edit "$(edit_json MultiEdit "$src/OrderDTO.java")"
check "a managed file with CRLF line ends is refused" denied
run pre-edit "$(edit_json Edit "$src/BomDTO.java")"
check "a managed file with a UTF-8 BOM is refused" denied

for owned in ProductService ProductController ProductServiceTest ProductMapper; do
    run pre-edit "$(edit_json Edit "$src/$owned.java")"
    check "developer-owned $owned.java may be edited (every form of the ownership line)" quiet
done
run pre-edit "$(edit_json Edit "$src/ProductRepository.java")"
check "a file with a preserved block may be edited" quiet
run pre-edit "$(edit_json Edit "$src/ShopApplication.java")"
check "a hand-written file may be edited" quiet
run pre-edit "$(edit_json Write "$src/NewThing.java")"
check "a new file may be written" quiet

block='    void touch();\n    // !----------------------------------------\n    java.util.List<Object> findByName(String name);\n    // ----------------------------------------!'
run pre-edit "$(edit_json Edit "$src/OrderRepository.java" s1 '    void touch();' "$block")"
check "adding one whole preserved block to a managed file goes through" quiet
run pre-edit "$(edit_json Edit "$src/OrderRepository.java" s1 '    void touch();' '    void touch();\n    void more();')"
check "adding code outside a block is refused" denied
run pre-edit "$(edit_json Edit "$src/OrderRepository.java" s1 '    void touch();' "$block\\n    void more();")"
check "a block with extra code after it is refused" denied

run pre-edit "$(edit_json Edit "$blueprint/schema.yml")"
check "blueprint/schema.yml is refused: rewritten on every generation" denied
run pre-edit "$(edit_json Edit "$blueprint/elasticore-dsl-guide.md")"
check "a copied guide is refused" denied
run pre-edit "$(edit_json Edit "$i18n/shop-messages.properties")"
check "the default messages file is refused" eval 'denied && has "$out" "messages_ko.properties"'
run pre-edit "$(edit_json Edit "$i18n/shop-messages_ko.properties")"
check "a translation, even one copied with the header, may be edited" quiet
run pre-edit "$(edit_json Edit "$model")"
check "the DSL may be edited" quiet
run pre-edit "$(edit_json Edit "$work/README.md")"
check "a file the generator never writes is not even read" quiet

out="$(printf '%s' "$(edit_json Edit "$managed")" | ELASTICORE_ALLOW_GENERATED_EDITS=1 "$shell" "$hook" pre-edit 2>"$work/stderr")"; rc=$?; err="$(cat "$work/stderr")"
check "ELASTICORE_ALLOW_GENERATED_EDITS=1 lets the edit through" quiet

json="$(printf '{"session_id":"s1","tool_name":"Write","tool_input":{"file_path":"%s","content":"{\\"file_path\\":\\"%s\\"}"}}' "$src/ShopApplication.java" "$managed")"
run pre-edit "$json"
check "a file_path inside the content is not the edited file" quiet
run pre-edit '{"session_id":"s1","tool_name":"Edit","tool_input":{}}'
check "no file_path: nothing to check" quiet

if command -v cygpath >/dev/null 2>&1; then
    windows="$(cygpath -w "$managed" | sed 's#\\#\\\\#g')"
    run pre-edit "$(edit_json Edit "$windows")"
    check "a Windows path (C:\\\\...) is read" denied
    check "and the refusal is still valid JSON" valid_json
fi

# --- pre-bash: no -Pforce without the user ---------------------------------------
run pre-bash "$(bash_json "./gradlew elcore3 -Pforce" "")"
check "a Gradle run with -Pforce is refused" eval 'denied && has "$out" "Ask the user"'
out="$(printf '%s' "$(bash_json "./gradlew elcore3 -Pforce" "")" | ELASTICORE_ALLOW_FORCE=1 "$shell" "$hook" pre-bash 2>"$work/stderr")"; rc=$?; err="$(cat "$work/stderr")"
check "ELASTICORE_ALLOW_FORCE=1 lets it through" quiet
run pre-bash "$(bash_json "grep -n -- -Pforce notes.txt" "")"
check "-Pforce in a command that is not Gradle is left alone" quiet
run pre-bash "$(bash_json "./gradlew compileJava" "")"
check "an ordinary Gradle run is left alone" quiet

# --- post-edit: a DSL change is noted, and Claude is told what to run --------
run post-edit "$(edit_json Edit "$model")"
check "a DSL edit tells Claude to generate and compile" eval 'noted && has "$out" "compileJava"'
check "a DSL edit is remembered for the session" [ -f "$marker" ]
check "the context is valid JSON" valid_json
run post-edit "$(edit_json Edit "$model")"
check "the reminder is given once per change" quiet

run post-edit "$(edit_json Edit "$blueprint/schema.yml" s2)"
check "blueprint/schema.yml is not the model" eval 'quiet && [ ! -f "$CLAUDE_PLUGIN_DATA/dsl-changed-s2" ]'

run post-edit "$(edit_json Edit "$legacy_rules" s3)"
check "access rules on the 2.x generator are called out" eval 'noted && has "$out" "2.x generator" && has "$out" "@access"'
run post-edit "$(edit_json Edit "$legacy_rules" s3)"
check "and only once per session" quiet
run post-edit "$(edit_json Edit "$rules" s4)"
check "the same rules on the rule engine are not called out" eval 'noted && ! has "$out" "2.x generator"'

run post-edit "$(edit_json Edit "$engine/build.gradle" s5)"
check "an edit to the elasticore build script counts as a model change" [ -f "$CLAUDE_PLUGIN_DATA/dsl-changed-s5" ]

run post-edit "$(edit_json Edit "$src/ProductRepository.java")"
check "an edit to a file with a preserved block gets the block rule, per generator" eval 'has "$out" "survives regeneration" && has "$out" "elcore3"'
run post-edit "$(edit_json Edit "$src/ShopApplication.java")"
check "an edit to a hand-written file says nothing" quiet

# --- post-bash: what the generator printed --------------------------------------
run post-bash "$(bash_json "./gradlew compileJava" "> Task :elcore3\\n[elcore3] DSL validation warnings:\\n  [shop] Product.weight: unresolved type\\n=== elcore3: 1 written / 0 unchanged / 0 skipped / 0 failed ===\\nBUILD SUCCESSFUL in 9s")"
check "rule-engine DSL validation warnings are reported" eval 'noted && has "$out" "rule engine"'
check "warnings keep the note" [ -f "$marker" ]

run post-bash "$(bash_json "./gradlew compileJava" "> Task :elcore\\nModelExtractor execution mode: default\\n[WARN] DSL Validation Warnings:\\n  [shop] Product.weight: unresolved type\\n[ERROR] DSL Validation: 1 warning(s) found.\\nBUILD FAILED in 3s")"
check "2.x DSL validation warnings are reported as a stopped build" eval 'noted && has "$out" "stopped the build"'
check "a failed build keeps the note" [ -f "$marker" ]

# Each case: label ~ command ~ stdout ~ extra tool_input fields ~ extra tool_response fields
for case in \
    "background~./gradlew compileJava~$built3~,\"run_in_background\":true~" \
    "interrupted~./gradlew compileJava~$built3~~,\"interrupted\":true" \
    "cut by head~./gradlew compileJava 2>&1 | head -40~> Task :elcore3\\n=== elcore3: 1 written / 0 unchanged / 0 skipped / 0 failed ===~~" \
    "filtered by grep~./gradlew compileJava 2>&1 | grep -E 'error|warning'~warning: [deprecation] x~~" \
    "dry run~./gradlew compileJava --dry-run~:compileJava SKIPPED\\nBUILD SUCCESSFUL~~" \
    "help for a task~./gradlew help --task compileJava~BUILD SUCCESSFUL~~" \
    "grep in build.gradle~grep -n test build.gradle~12: test {~~" \
    "cat build.gradle into grep~cat build.gradle | grep -n test~12: test {~~" \
    "ls and cat~ls build && cat settings.gradle~rootProject.name~~" \
    "failed build~./gradlew compileJava~> Task :compileJava FAILED\\nBUILD FAILED in 3s~~"
do
    IFS='~' read -r label command stdout input_extra response_extra <<EOF
$case
EOF
    run post-bash "$(bash_json "$command" "$stdout" s1 "$input_extra" "$response_extra")"
    check "the note stays after: $label" [ -f "$marker" ]
done

run post-bash "$(bash_json "./gradlew elcore3" "dto  src/x/ProductDTO.java  SKIP(user-modified; -Pforce to overwrite)\\n=== elcore3: 0 written / 41 unchanged / 15 skipped / 0 failed ===\\nBUILD SUCCESSFUL in 6s")"
check "hand-edited generated files are reported, with asking first" eval 'noted && has "$out" "edited by hand" && has "$out" "ask before restoring"'
check "a successful generating build clears the note even with such files" [ ! -f "$marker" ]

run post-edit "$(edit_json Edit "$model")"
run post-bash "$(bash_json "./gradlew compileJava" "> Task :elcore\\nModelExtractor execution mode: default\\n[WARN] Externally Modified Files Detected:\\n  ProductDTO.java\\nBUILD SUCCESSFUL in 6s")"
check "2.x hand-edited files are reported" eval 'noted && has "$out" "edited by hand"'
check "a successful 2.x build clears the note" [ ! -f "$marker" ]

run post-bash "$(bash_json "./gradlew elcore3" "control  src/x/ShopController.java  SKIP(no ElastiCORE header - yours)\\n$built3")"
check "a file without a header where one is generated is reported" eval 'noted && has "$out" "no ElastiCORE header"'

run post-edit "$(edit_json Edit "$model")"
run post-bash "$(bash_json "./gradlew compileJava" "$built3")"
check "a clean rule-engine build clears the note and says nothing" eval 'quiet && [ ! -f "$marker" ]'
run post-edit "$(edit_json Edit "$model")"
run post-bash "$(bash_json "gradle :app:compileJava" "$built2")"
check "a clean 2.x build through gradle :module:task clears the note" eval 'quiet && [ ! -f "$marker" ]'

# --- stop: no finishing while a DSL change has not been built -------------------
run stop "$(stop_json false)"
check "with no DSL change, Claude may stop" quiet

run post-edit "$(edit_json Write "$model")"
run stop "$(stop_json false)"
check "after an unbuilt DSL change, Claude is sent back to build once" eval 'noted && has "$out" "\"hookEventName\":\"Stop\"" && has "$out" "compileJava"'
check "the reason is valid JSON" valid_json
run stop "$(stop_json false)"
check "the reminder is not repeated" quiet

run post-edit "$(edit_json Write "$model")"
run stop "$(stop_json true)"
check "stop_hook_active lets Claude stop" quiet
check "and keeps the note for the next stop" [ -f "$marker" ]

run post-bash "$(bash_json "./gradlew compileJava" "$built3")"
run post-edit "$(edit_json Write "$model" other)"
run stop "$(stop_json false s1)"
check "another session's DSL change does not hold this one" quiet
run stop "$(stop_json false other)"
check "it holds the session that made it" eval 'has "$out" "compileJava"'

# --- unknown or empty input -------------------------------------------------------
run unknown-event '{}'
check "an unknown event does nothing" quiet
out="$("$shell" "$hook" pre-edit </dev/null 2>/dev/null)"; rc=$?
check "empty input does nothing" [ "$rc" -eq 0 ]

printf '%d passed, %d failed (bash %s; fixtures in %s)\n' "$passed" "$failed" "$("$shell" -c 'echo $BASH_VERSION')" "$work"
[ "$failed" -eq 0 ]
