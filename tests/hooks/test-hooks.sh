#!/usr/bin/env bash
# Feeds the plugin's hook script the JSON Claude Code sends and checks what it
# answers. Runs with the same tools the hook gets: bash and POSIX utilities, on
# Linux, macOS and Git Bash on Windows.
#
# usage: bash tests/hooks/test-hooks.sh
# The fixtures go to a fresh directory under $TMPDIR, left for inspection.

set -u
here="$(cd "$(dirname "$0")" && pwd)"
hook="$here/../../plugins/elasticore/hooks/elasticore-hook.sh"
work="$(mktemp -d "${TMPDIR:-/tmp}/elasticore-hook-test.XXXXXX")"
export CLAUDE_PLUGIN_DATA="$work/data"
unset ELASTICORE_ALLOW_GENERATED_EDITS

passed=0
failed=0

# --- fixtures: one file of each kind the generator distinguishes -------------
src="$work/project/src/main/java/com/acme/shop"
dsl="$work/project/src/main/resources/blueprint/shop/model"
mkdir -p "$src" "$dsl"
printf '//ecd:-1375193215H20261020123214_V3.0\npackage com.acme.shop;\n\npublic class ProductDTO {}\n' > "$src/ProductDTO.java"
printf '//ecd:1883886029H20261020123214_V3.0\r\npackage com.acme.shop;\r\n\r\npublic class OrderDTO {}\r\n' > "$src/OrderDTO.java"
printf '//ecd:1883886029H20261020123214_V3.0\n// Initially generated by ElastiCORE; no longer managed - do not remove this line.\npackage com.acme.shop;\n\npublic class ProductService {}\n' > "$src/ProductService.java"
printf '//ecd:-901H20261020123214_V3.0\npackage com.acme.shop;\n\ninterface ProductRepository {\n// !-----------------------------------------------------------\n// ------------------------------------------------------------!\n}\n' > "$src/ProductRepository.java"
printf 'package com.acme.shop;\n\npublic class ShopApplication {}\n' > "$src/ShopApplication.java"
printf 'entity:\n  Product:\n    fields:\n      name: string(100)!\n' > "$dsl/entity.yml"

managed="$src/ProductDTO.java"
managed_crlf="$src/OrderDTO.java"
owned="$src/ProductService.java"
block="$src/ProductRepository.java"
hand="$src/ShopApplication.java"
model="$dsl/entity.yml"

# --- helpers -------------------------------------------------------------------
run() {  # run <event> <json>  -> sets rc, out, err
    out="$(printf '%s' "$2" | bash "$hook" "$1" 2>"$work/stderr")"
    rc=$?
    err="$(cat "$work/stderr")"
}

check() {  # check <name> <condition...>
    name="$1"; shift
    if "$@"; then
        passed=$((passed + 1))
    else
        failed=$((failed + 1))
        printf 'FAIL %s\n  rc=%s\n  stdout=%s\n  stderr=%s\n' "$name" "$rc" "$out" "$err"
    fi
}

has() { case "$1" in *"$2"*) return 0 ;; esac; return 1; }

denied() { [ "$rc" -eq 0 ] && has "$out" '"permissionDecision":"deny"'; }
quiet() { [ "$rc" -eq 0 ] && [ -z "$out$err" ]; }
valid_json() {
    command -v python3 >/dev/null 2>&1 || return 0
    python3 -c 'import json,sys; json.loads(sys.argv[1])' "$out" 2>/dev/null
}

edit_json() {  # edit_json <tool> <path> [session]
    printf '{"session_id":"%s","hook_event_name":"PreToolUse","tool_name":"%s","tool_input":{"file_path":"%s","old_string":"a","new_string":"b"}}' "${3:-s1}" "$1" "$2"
}

bash_json() {  # bash_json <command> <stdout> [session]
    printf '{"session_id":"%s","hook_event_name":"PostToolUse","tool_name":"Bash","tool_input":{"command":"%s"},"tool_response":{"stdout":"%s","stderr":"","interrupted":false,"isImage":false}}' "${3:-s1}" "$1" "$2"
}

stop_json() {  # stop_json <active> [session]
    printf '{"session_id":"%s","hook_event_name":"Stop","stop_hook_active":%s}' "${2:-s1}" "$1"
}

marker="$CLAUDE_PLUGIN_DATA/dsl-changed-s1"

# --- pre-edit: generated files are changed through the DSL ---------------------
run pre-edit "$(edit_json Edit "$managed")"
check "managed file is refused" denied
check "the refusal names the file and the DSL" eval 'has "$out" "$managed" && has "$out" "src/main/resources/blueprint"'
check "the refusal is valid JSON" valid_json

run pre-edit "$(edit_json Write "$managed")"
check "overwriting a managed file is refused" denied

run pre-edit "$(edit_json MultiEdit "$managed_crlf")"
check "a managed file with CRLF line ends is refused" denied

run pre-edit "$(edit_json Edit "$owned")"
check "a developer-owned file may be edited" quiet

run pre-edit "$(edit_json Edit "$block")"
check "a file with a preserved block may be edited" quiet

run pre-edit "$(edit_json Edit "$hand")"
check "a hand-written file may be edited" quiet

run pre-edit "$(edit_json Write "$src/NewThing.java")"
check "a new file may be written" quiet

out="$(printf '%s' "$(edit_json Edit "$managed")" | ELASTICORE_ALLOW_GENERATED_EDITS=1 bash "$hook" pre-edit 2>"$work/stderr")"; rc=$?; err="$(cat "$work/stderr")"
check "ELASTICORE_ALLOW_GENERATED_EDITS=1 lets the edit through" quiet

json="$(printf '{"session_id":"s1","tool_name":"Write","tool_input":{"file_path":"%s","content":"{\\"file_path\\":\\"%s\\"}"}}' "$hand" "$managed")"
run pre-edit "$json"
check "a file_path inside the content is not the edited file" quiet

run pre-edit '{"session_id":"s1","tool_name":"Edit","tool_input":{}}'
check "no file_path: nothing to check" quiet

if command -v cygpath >/dev/null 2>&1; then
    windows="$(cygpath -w "$managed" | sed 's#\\#\\\\#g')"
    run pre-edit "$(edit_json Edit "$windows")"
    check "a Windows path (C:\\\\...) is read" denied
    check "and the refusal is still valid JSON" valid_json
fi

# --- post-edit: a DSL change is noted, and Claude is told what to run --------
run post-edit "$(edit_json Edit "$model")"
check "a DSL edit tells Claude to generate and compile" eval '[ "$rc" -eq 0 ] && has "$out" "additionalContext" && has "$out" "compileJava"'
check "a DSL edit is remembered for the session" [ -f "$marker" ]
check "the context is valid JSON" valid_json

run post-edit "$(edit_json Edit "$model")"
check "the reminder is given once per change" eval '[ "$rc" -eq 0 ] && [ -z "$out" ]'

run post-edit "$(edit_json Edit "$block")"
check "an edit to a file with a preserved block gets the block rule" eval 'has "$out" "survives regeneration"'

run post-edit "$(edit_json Edit "$hand")"
check "an edit to a hand-written file says nothing" eval '[ "$rc" -eq 0 ] && [ -z "$out" ]'

# --- post-bash: what the generator printed --------------------------------------
run post-bash "$(bash_json "./gradlew compileJava" "> Task :elcore3\\n[elcore3] DSL validation warnings:\\n  [shop] Product.weight: unresolved type\\nBUILD SUCCESSFUL in 9s")"
check "DSL validation warnings are reported" eval 'has "$out" "DSL validation warnings" && has "$out" "additionalContext"'
check "warnings keep the note" [ -f "$marker" ]

run post-bash "$(bash_json "./gradlew elcore3" "dto  src/x/ProductDTO.java  SKIP(user-modified; -Pforce to overwrite)\\nBUILD SUCCESSFUL")"
check "hand-edited generated files are reported" eval 'has "$out" "edited by hand" && has "$out" "-Pforce"'

run post-bash "$(bash_json "./gradlew compileJava" "> Task :compileJava FAILED\\nBUILD FAILED in 3s")"
check "a failed build keeps the note" [ -f "$marker" ]

run post-bash "$(bash_json "grep -n DSL validation warnings build.log" "nothing")"
check "a command that is not a Gradle build is ignored" eval '[ "$rc" -eq 0 ] && [ -z "$out" ] && [ -f "$marker" ]'

run post-bash "$(bash_json "./gradlew dependencies" "BUILD SUCCESSFUL")"
check "a Gradle task that does not generate is ignored" [ -f "$marker" ]

run post-bash "$(bash_json "./gradlew compileJava 2>&1 | grep -i 'DSL validation warnings'" "BUILD SUCCESSFUL in 4s")"
check "a clean build clears the note, even when the command names the header" eval '[ -z "$out" ] && [ ! -f "$marker" ]'

# --- stop: no finishing while a DSL change has not been built -------------------
run stop "$(stop_json false)"
check "with no DSL change, Claude may stop" quiet

run post-edit "$(edit_json Write "$model")"
run stop "$(stop_json false)"
check "after an unbuilt DSL change, Claude is sent back to build once" eval '[ "$rc" -eq 0 ] && has "$out" "\"hookEventName\":\"Stop\"" && has "$out" "compileJava"'
check "the reason is valid JSON" valid_json
run stop "$(stop_json false)"
check "the reminder is not repeated" quiet

run post-edit "$(edit_json Write "$model")"
run stop "$(stop_json true)"
check "stop_hook_active lets Claude stop" quiet
check "and keeps the note for the next stop" [ -f "$marker" ]

run post-bash "$(bash_json "./gradlew compileJava" "BUILD SUCCESSFUL in 5s")"
run post-edit "$(edit_json Write "$model" other)"
run stop "$(stop_json false s1)"
check "another session's DSL change does not hold this one" quiet
run stop "$(stop_json false other)"
check "it holds the session that made it" eval 'has "$out" "compileJava"'

# --- unknown or empty input -------------------------------------------------------
run unknown-event '{}'
check "an unknown event does nothing" [ "$rc" -eq 0 ]
out="$(bash "$hook" pre-edit </dev/null 2>/dev/null)"; rc=$?
check "empty input does nothing" [ "$rc" -eq 0 ]

printf '%d passed, %d failed (fixtures in %s)\n' "$passed" "$failed" "$work"
[ "$failed" -eq 0 ]
