def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gradle", default=os.environ.get("GRADLE", "gradle"))
    parser.add_argument("--bash", default=os.environ.get("HOOK_BASH") or default_bash())
    parser.add_argument("--java", default=default_java())
    parser.add_argument("--work")
    args = parser.parse_args()

    version = os.environ.get("ELASTICORE_VERSION") or newest_3x()
    work = args.work or tempfile.mkdtemp(prefix="elasticore-contract-")
    print("ElastiCORE %s, projects in %s" % (version, work), flush=True)
    gradle = args.gradle.split()
    temp = os.path.join(work, "tmp")
    os.makedirs(temp, exist_ok=True)
    data = os.path.join(work, "hook-data")

    def run(project, *tasks):
        try:
            p = subprocess.run(gradle + list(tasks) + ["--console=plain"], cwd=project, capture_output=True,
                               text=True, encoding="utf-8", errors="replace", timeout=GRADLE_TIMEOUT)
            return p.returncode, re.sub(r"\x1b\[[0-9;]*m", "", p.stdout + p.stderr)
        except subprocess.TimeoutExpired:
            return -1, "timed out after %d s" % GRADLE_TIMEOUT

    def hook(event, payload):
        p = subprocess.run([args.bash, HOOK, event], input=json.dumps(payload, ensure_ascii=False),
                           capture_output=True, text=True, encoding="utf-8", timeout=60,
                           env=dict(os.environ, CLAUDE_PLUGIN_DATA=data))
        return p.returncode, p.stdout, p.stderr

    def bash_payload(session, command, out, rc=0):
        """What Claude Code sends after a command: PostToolUse, or PostToolUseFailure when it exited non-zero."""
        if rc != 0:
            # Claude Code passes on the first 10,000 characters of a failed command's output.
            return {"session_id": session, "hook_event_name": "PostToolUseFailure", "tool_name": "Bash",
                    "tool_input": {"command": command}, "error": "Exit code %d\n%s" % (rc, out[:10000]),
                    "is_interrupt": False}
        return {"session_id": session, "hook_event_name": "PostToolUse", "tool_name": "Bash",
                "tool_input": {"command": command},
                "tool_response": {"stdout": out, "stderr": "", "interrupted": False, "isImage": False}}

    def edit_payload(session, path):
        return {"session_id": session, "tool_name": "Edit",
                "tool_input": {"file_path": path, "old_string": "a", "new_string": "b"}}

