"""Checks, against real builds, the ElastiCORE behaviour this kit relies on.

The skill, the agents and the hooks assume a number of things about ElastiCORE:
how a generated file is marked, what each generator prints, which guides it
copies into a project, which tasks its Gradle plugin adds, what the new-project
template does in a browser. This builds the template from
references/new-project.md and the example from references/example-order.md
with the ElastiCORE release under test - the newest 3.x on Maven Central
unless ELASTICORE_VERSION names one - and a second project on the 2.x
generator, and fails, naming the assumption and where the kit states it, as
soon as one no longer holds.

usage: python tests/contract/check.py [--gradle GRADLE] [--bash BASH] [--java JAVA] [--work DIR]
  GRADLE  the Gradle command, Gradle 8.14 or later (default: gradle on the PATH)
  BASH    the bash that runs the hook script (default: Git Bash on Windows, else bash on the PATH)
  JAVA    the java that runs the built application (default: JAVA_HOME's, else java on the PATH)
  DIR     an empty directory for the projects (default: a new temporary one, kept)
"""
import argparse
import json
import os
import re
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request

KIT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PLUGIN = os.path.join(KIT, "plugins", "elasticore")
REFERENCES = os.path.join(PLUGIN, "skills", "elasticore", "references")
SKILL = os.path.join(PLUGIN, "skills", "elasticore", "SKILL.md")
NEW_PROJECT = os.path.join(REFERENCES, "new-project.md")
EXAMPLE = os.path.join(REFERENCES, "example-order.md")
RECIPE_BOARD = os.path.join(REFERENCES, "recipe-board.md")
QUICK_REFERENCE = os.path.join(REFERENCES, "quick-reference.md")
RUN_AND_CHECK = os.path.join(REFERENCES, "run-and-check.md")
HOOK = os.path.join(PLUGIN, "hooks", "elasticore-hook.sh")
METADATA = "https://repo1.maven.org/maven2/io/elasticore/elasticore-base/maven-metadata.xml"

OWNED_PREFIX = "// Initially generated by ElastiCORE;"
SUMMARY = re.compile(r"=== elcore3: (\d+) written / (\d+) unchanged / (\d+) skipped / (\d+) failed ===")
GRADLE_TIMEOUT = 900

results = []


def check(name, ok, where, detail=""):
    results.append((bool(ok), name, where, detail))
    if ok:
        print("PASS  " + name, flush=True)
    else:
        print("FAIL  " + name + "\n      the kit relies on it in: " + where
              + ("\n      " + detail if detail else ""), flush=True)
    return bool(ok)


def newest_3x():
    request = urllib.request.Request(METADATA, headers={"User-Agent": "elasticore-agent-kit"})
    with urllib.request.urlopen(request, timeout=60) as response:
        text = response.read().decode("utf-8")
    versions = [v for v in re.findall(r"<version>([^<]+)</version>", text) if v.startswith("3.")]
    if not versions:
        sys.exit("no 3.x version in " + METADATA)
    return versions[-1]


def blocks_by_heading(path):
    """The code block under each '## `name`' heading of a reference page."""
    with open(path, encoding="utf-8") as f:
        text = f.read()
    return dict(re.findall(r"^## `([^`]+)`\s*\n+```\w*\n(.*?)```", text, re.S | re.M))


def guides_named_in_skill():
    with open(SKILL, encoding="utf-8") as f:
        section = f.read().split("## 1.", 1)[1].split("## 2.", 1)[0]
    return sorted(set(re.findall(r"`(elasticore-[\w-]+\.md)`", section)))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def find(root, name):
    for directory, _, files in os.walk(root):
        if name in files:
            return os.path.join(directory, name)
    return None


def kind(path):
    """The ownership rule the skill states, applied here independently."""
    text = read(path)
    if not text.startswith("//ecd:"):
        return "hand"
    if OWNED_PREFIX in text[:600]:
        return "owned"
    return "block" if "// !----------" in text else "managed"


def status_of(output, file_name):
    for line in output.splitlines():
        if file_name in line:
            found = re.search(r"\s(WROTE|UNCHANGED|SKIP\([^)]*\)|REGENERATED\([^)]*\)|REMOVED\([^)]*\)|ERROR.*)\s*$", line)
            if found:
                return found.group(1)
    return None


def default_bash():
    if os.name == "nt":
        for candidate in (r"C:\Program Files\Git\bin\bash.exe", r"C:\Program Files\Git\usr\bin\bash.exe"):
            if os.path.isfile(candidate):
                return candidate
    return shutil.which("bash") or "bash"


def default_java():
    home = os.environ.get("JAVA_HOME")
    if home:
        exe = os.path.join(home, "bin", "java.exe" if os.name == "nt" else "java")
        if os.path.isfile(exe):
            return exe
    return shutil.which("java") or "java"


def free_port():
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gradle", default=os.environ.get("GRADLE", "gradle"))
    parser.add_argument("--bash", default=os.environ.get("HOOK_BASH") or default_bash())
    parser.add_argument("--java", default=default_java())
    parser.add_argument("--work")
    args = parser.parse_args()

    version = os.environ.get("ELASTICORE_VERSION") or newest_3x()
    work = args.work or tempfile.mkdtemp(prefix="elasticore-contract-")
    print("ElastiCORE %s, projects in %s" % (version, work), flush=True)
    gradle = args.gradle.split()
    temp = os.path.join(work, "tmp")
    os.makedirs(temp, exist_ok=True)
    data = os.path.join(work, "hook-data")

    def run(project, *tasks):
        try:
            p = subprocess.run(gradle + list(tasks) + ["--console=plain"], cwd=project, capture_output=True,
                               text=True, encoding="utf-8", errors="replace", timeout=GRADLE_TIMEOUT)
            return p.returncode, re.sub(r"\x1b\[[0-9;]*m", "", p.stdout + p.stderr)
        except subprocess.TimeoutExpired:
            return -1, "timed out after %d s" % GRADLE_TIMEOUT

    def hook(event, payload):
        p = subprocess.run([args.bash, HOOK, event], input=json.dumps(payload, ensure_ascii=False),
                           capture_output=True, text=True, encoding="utf-8", timeout=60,
                           env=dict(os.environ, CLAUDE_PLUGIN_DATA=data))
        return p.returncode, p.stdout, p.stderr

    def bash_payload(session, command, out, rc=0):
        """What Claude Code sends after a command: PostToolUse, or PostToolUseFailure when it exited non-zero."""
        if rc != 0:
            # Claude Code passes on the first 10,000 characters of a failed command's output.
            return {"session_id": session, "hook_event_name": "PostToolUseFailure", "tool_name": "Bash",
                    "tool_input": {"command": command}, "error": "Exit code %d\n%s" % (rc, out[:10000]),
                    "is_interrupt": False}
        return {"session_id": session, "hook_event_name": "PostToolUse", "tool_name": "Bash",
                "tool_input": {"command": command},
                "tool_response": {"stdout": out, "stderr": "", "interrupted": False, "isImage": False}}

    def edit_payload(session, path):
        return {"session_id": session, "tool_name": "Edit",
                "tool_input": {"file_path": path, "old_string": "a", "new_string": "b"}}

    # --- the new-project template, built as written -------------------------------
    template = blocks_by_heading(NEW_PROJECT)
    wanted = ["build.gradle", "settings.gradle", "src/main/java/com/acme/shop/ShopApplication.java",
              "src/main/resources/blueprint/shop/env.yml", "src/main/resources/blueprint/shop/model/entity.yml"]
    check("new-project.md has the five files of the template", sorted(template) == wanted,
          "references/new-project.md", "found: %s" % sorted(template))
    wrapped = os.path.join(work, "wrapper")
    write(os.path.join(wrapped, "settings.gradle"), template.get("settings.gradle", ""))
    rc, out = run(wrapped, "wrapper", "--gradle-version", "8.14.3")
    check("the Gradle wrapper is made with settings.gradle alone, before build.gradle exists",
          rc == 0 and os.path.isfile(os.path.join(wrapped, "gradlew")), "references/new-project.md",
          "exit %d: %s" % (rc, out.strip()[-300:]))
    project = os.path.join(work, "shop")
    for name, text in template.items():
        write(os.path.join(project, name), text.replace("VERSION", version))
    model = os.path.join(project, "src", "main", "resources", "blueprint", "shop", "model")
    blueprint = os.path.dirname(os.path.dirname(model))
    java = os.path.join(project, "src", "main", "java")

    rc, out = run(project, "compileJava")
    write(os.path.join(work, "template.log"), out)
    check("the new-project template generates and compiles as written", rc == 0 and SUMMARY.search(out),
          "references/new-project.md", "exit %d; see %s" % (rc, os.path.join(work, "template.log")))
    check("the template has no DSL validation warning", "DSL validation warnings" not in out,
          "references/new-project.md")

    # --- the example on top of it -----------------------------------------------------
    example = blocks_by_heading(EXAMPLE)
    check("example-order.md has the three model files",
          sorted(example) == ["model/dto.yml", "model/enum.yml", "model/order.yml"],
          "references/example-order.md", "found: %s" % sorted(example))
    for name, text in example.items():
        write(os.path.join(model, os.path.basename(name)), text)
    rc, out = run(project, "compileJava")
    write(os.path.join(work, "example.log"), out)
    summary = SUMMARY.search(out)
    check("compileJava generates first and the example compiles", rc == 0 and summary,
          "SKILL.md section 4; references/example-order.md", "exit %d; see %s" % (rc, os.path.join(work, "example.log")))
    check("the rule engine prints its summary line, with 0 failed", summary and summary.group(4) == "0",
          "SKILL.md section 5; skills/generate")
    check("the example has no DSL validation warning", "DSL validation warnings" not in out,
          "references/example-order.md")

    rc_hook, note, _ = hook("post-edit", edit_payload("built", os.path.join(model, "order.yml")))
    _, after, _ = hook("post-bash", bash_payload("built", "./gradlew compileJava", out))
    marker = os.path.join(data, "dsl-changed-built")
    check("the hook takes this real output as a successful generating build",
          "compileJava" in note and not os.path.exists(marker) and not after.strip(),
          "hooks/elasticore-hook.sh post-edit and post-bash", "after: %s" % after.strip()[:200])

    # --- the guides the skill sends the agent to ----------------------------------------
    missing = [g for g in guides_named_in_skill() if not os.path.isfile(os.path.join(blueprint, g))]
    check("every guide SKILL.md names is copied into blueprint/", not missing,
          "SKILL.md section 1", "missing: %s" % missing)

    # --- how files are marked ----------------------------------------------------------
    expected = {"ProductDTO.java": "managed", "ProductService.java": "owned",
                "PurchaseOrderBase.java": "managed", "PurchaseOrder.java": "owned",
                "PurchaseOrderService.java": "owned", "PurchaseOrderController.java": "owned",
                "ShopApiErrors.java": "owned"}
    for name, want in expected.items():
        path = find(java, name)
        got = kind(path) if path else "missing"
        check("%s is %s" % (name, want), got == want,
              "SKILL.md section 2; references/example-order.md; hooks/elasticore-hook.sh classify()",
              "found: %s" % got)
    ids = [p for p in (find(java, "PurchaseOrderBase.java"), find(java, "OrderLine.java")) if p]
    check("@genid on string(36) generates IdUtils.newId(36)",
          ids and all("IdUtils.newId(36)" in read(p) for p in ids), "SKILL.md section 8")
    schema = os.path.join(blueprint, "schema.yml")
    messages = os.path.join(project, "src", "main", "resources", "i18n", "shop-messages.properties")
    check("blueprint/schema.yml and the default messages file are generated, with the headers the hook reads",
          os.path.isfile(schema) and read(schema).startswith("# Generated Schema File")
          and os.path.isfile(messages) and "Generated by ElastiCORE" in read(messages)[:300],
          "SKILL.md section 2; hooks/elasticore-hook.sh classify()")

    # --- the hook on files the generator really wrote ---------------------------------------
    dto = find(java, "ProductDTO.java")
    owned = find(java, "ProductService.java")
    if dto and owned:
        decisions = []
        for path in (dto, owned, schema, messages):
            rc_one, out_one, _ = hook("pre-edit", edit_payload("contract", path))
            try:
                decisions.append(json.loads(out_one)["hookSpecificOutput"]["permissionDecision"])
            except (ValueError, KeyError, TypeError):
                decisions.append("allow" if rc_one == 0 and not out_one.strip() else "error")
        check("the hook refuses the generated files and allows the owned one",
              decisions == ["deny", "allow", "deny", "deny"], "hooks/elasticore-hook.sh pre-edit",
              "generated DTO, owned service, schema.yml, messages: %s" % decisions)

    # --- the owned file is left alone ---------------------------------------------------------
    if owned:
        with open(owned, "a", encoding="utf-8", newline="\n") as f:
            f.write("// business logic\n")
        rc, out = run(project, "elcore3")
        check("an edited developer-owned file is reported SKIP(user-owned) and kept",
              status_of(out, "ProductService.java") == "SKIP(user-owned)" and "// business logic" in read(owned),
              "SKILL.md sections 2 and 5", "status: %s" % status_of(out, "ProductService.java"))

    # --- a hand edit to a generated file, and how it is undone -----------------------------
    if dto:
        with open(dto, "a", encoding="utf-8", newline="\n") as f:
            f.write("// edited by hand\n")
        rc, out = run(project, "elcore3")
        check("a hand-edited generated file is reported SKIP(user-modified; -Pforce to overwrite)",
              status_of(out, "ProductDTO.java") == "SKIP(user-modified; -Pforce to overwrite)",
              "SKILL.md sections 2 and 5; hooks/elasticore-hook.sh post-bash",
              "status: %s" % status_of(out, "ProductDTO.java"))
        _, note, _ = hook("post-bash", bash_payload("contract", "./gradlew elcore3", out))
        check("the hook recognises that report in real output", "edited by hand" in note,
              "hooks/elasticore-hook.sh post-bash", "hook said: %s" % note.strip()[:200])
        os.remove(dto)
        rc, out = run(project, "elcore3")
        check("deleting a generated file and generating again restores it",
              status_of(out, "ProductDTO.java") == "WROTE" and kind(dto) == "managed", "SKILL.md section 5",
              "status: %s" % status_of(out, "ProductDTO.java"))

    # --- a preserved block survives regeneration --------------------------------------------
    entity = os.path.join(model, "entity.yml")
    original_entity = read(entity)
    if dto:
        text = read(dto)
        cut = text.rstrip().rfind("}")
        block = ("\n    // !-----------------------------------------------------------\n"
                 "    public String label() { return name; }\n"
                 "    // ------------------------------------------------------------!\n")
        write(dto, text[:cut] + block + text[cut:])
        write(entity, original_entity + "      stock:     int\n")
        rc, out = run(project, "elcore3")
        after_text = read(dto)
        check("a preserved block in a generated file survives a regeneration that rewrites the file",
              status_of(out, "ProductDTO.java") == "WROTE" and "label()" in after_text and "stock" in after_text,
              "SKILL.md section 2; hooks/elasticore-hook.sh adds_block()",
              "status: %s, block kept: %s, new field: %s" % (status_of(out, "ProductDTO.java"),
                                                             "label()" in after_text, "stock" in after_text))
        write(entity, original_entity)
        os.remove(dto)
        run(project, "elcore3")

    # --- what a DSL mistake looks like ------------------------------------------------------
    write(entity, original_entity + "      weight:    kilogramz\n")
    rc, out = run(project, "elcore3")
    check("an unknown type is listed under '[elcore3] DSL validation warnings:' and the build still passes",
          rc == 0 and "[elcore3] DSL validation warnings:" in out and "unresolved type 'kilogramz'" in out,
          "SKILL.md sections 4 and 5; agents; hooks/elasticore-hook.sh post-bash")
    _, note, _ = hook("post-bash", bash_payload("contract", "./gradlew elcore3", out))
    check("the hook recognises the warnings in real output", "rule engine" in note,
          "hooks/elasticore-hook.sh post-bash", "hook said: %s" % note.strip()[:200])
    write(entity, original_entity)
    run(project, "elcore3")

    # --- a YAML file that does not parse: left out, and the build passes ----------------------
    review = os.path.join(model, "review.yml")
    write(review, "entity:\n  Review:\n    meta: entity @root\n    fields:\n"
                  "      reviewId: long @id @sequence\n     text: string(200)\n")
    hook("post-edit", edit_payload("broken", review))
    rc, out = run(project, "compileJava")
    check("a YAML file that does not parse is printed as 'LOAD ERROR', left out, and the build passes",
          rc == 0 and "* LOAD ERROR: " in out and "YAMLException" in out and "BUILD SUCCESSFUL" in out
          and not find(java, "Review.java"),
          "SKILL.md section 5; hooks/elasticore-hook.sh post-bash", "exit %d" % rc)
    _, note, _ = hook("post-bash", bash_payload("broken", "./gradlew compileJava", out, rc))
    check("the hook reports it and keeps the note",
          "could not be read" in note and os.path.exists(os.path.join(data, "dsl-changed-broken")),
          "hooks/elasticore-hook.sh post-bash", "hook said: %s" % note.strip()[:200])
    os.remove(review)
    run(project, "elcore3")

    # --- a DTO the model no longer has: the generated file goes --------------------------
    dto_yml = os.path.join(model, "dto.yml")
    kept = read(dto_yml)
    line_dto = find(java, "OrderLineDTO.java")
    os.remove(dto_yml)
    rc, out = run(project, "elcore3")
    check("a generated file the DSL no longer produces is REMOVED(the DSL no longer produces it)",
          line_dto and status_of(out, "OrderLineDTO.java") == "REMOVED(the DSL no longer produces it)"
          and not os.path.exists(line_dto), "SKILL.md section 5",
          "status: %s" % status_of(out, "OrderLineDTO.java"))
    write(dto_yml, kept)
    run(project, "elcore3")

    # --- a DTO named in @dtype that nobody defines, in a fresh project -----------------------
    fresh = os.path.join(work, "fresh")
    for name, text in template.items():
        write(os.path.join(fresh, name), text.replace("VERSION", version))
    for name, text in example.items():
        if not name.endswith("dto.yml"):
            write(os.path.join(fresh, "src", "main", "resources", "blueprint", "shop", "model",
                               os.path.basename(name)), text)
    rc, out = run(fresh, "compileJava")
    check("without dto.yml generation warns unresolved type 'OrderLineDTO' and compileJava fails",
          rc != 0 and "unresolved type 'OrderLineDTO'" in out and "DSL validation warnings:" in out,
          "SKILL.md section 4; references/example-order.md")
    _, note, _ = hook("post-bash", bash_payload("fresh", "./gradlew compileJava", out, rc))
    check("the hook passes the warnings on from the failed build", "rule engine" in note,
          "hooks/elasticore-hook.sh post-bash (PostToolUseFailure)", "hook said: %s" % note.strip()[:200])

    # --- layered Java: the 2.x-compatible output on the rule engine ---------------------------
    layered = os.path.join(work, "layered")
    for name, text in template.items():
        if name == "build.gradle":
            text = re.sub(r"architecture = '\w+'", "architecture = 'layered'", text)
        write(os.path.join(layered, name), text.replace("VERSION", version))
    rc, out = run(layered, "compileJava")
    write(os.path.join(work, "layered.log"), out)
    check("on layered Java the generator warns that @access is not enforced",
          "DSL validation warnings:" in out and "@access" in out and "which the selected rules do not enforce" in out,
          "SKILL.md section 3; references/new-project.md", "see %s" % os.path.join(work, "layered.log"))
    check("on layered Java a money field does not compile ('package Money does not exist')",
          rc != 0 and "package Money does not exist" in out,
          "SKILL.md section 3; references/new-project.md - when this fails, ElastiCORE fixed it: update both",
          "exit %d; see %s" % (rc, os.path.join(work, "layered.log")))

    # --- the tasks the skill names ------------------------------------------------------------
    rc, out = run(project, "tasks", "--all")
    names = set(re.findall(r"^(\S+) - ", out, re.M))
    missing = [t for t in ("elcore", "elcore3", "elcore3ts") if t not in names]
    check("the Gradle plugin adds elcore, elcore3 and elcore3ts", rc == 0 and not missing,
          "SKILL.md section 4", "missing: %s" % missing)

    # --- the application in a browser ------------------------------------------------------
    rc, out = run(project, "bootJar")
    jars = [j for j in os.listdir(os.path.join(project, "build", "libs")) if not j.endswith("-plain.jar")] \
        if rc == 0 else []
    if check("bootJar builds the application", jars, "references/new-project.md"):
        port = free_port()
        base = "http://127.0.0.1:%d" % port
        log = open(os.path.join(work, "app.log"), "w", encoding="utf-8")
        app = subprocess.Popen([args.java, "-Djava.io.tmpdir=" + temp, "-jar",
                                os.path.join(project, "build", "libs", jars[0]), "--server.port=%d" % port],
                               stdout=log, stderr=subprocess.STDOUT)

        def call(method, path, body=None):
            data_bytes = json.dumps(body).encode("utf-8") if body is not None else None
            request = urllib.request.Request(base + path, data=data_bytes, method=method,
                                             headers={"Content-Type": "application/json"} if data_bytes else {})
            try:
                with urllib.request.urlopen(request, timeout=10) as response:
                    return response.status, response.geturl(), response.read().decode("utf-8", "replace")
            except urllib.error.HTTPError as e:
                return e.code, path, e.read().decode("utf-8", "replace")

        try:
            started = False
            deadline = time.time() + 180
            while time.time() < deadline and app.poll() is None:
                try:
                    if call("GET", "/v3/api-docs")[0] == 200:
                        started = True
                        break
                except OSError:
                    pass
                time.sleep(1)
            if check("the application starts", started, "references/new-project.md",
                     "see %s" % os.path.join(work, "app.log")):
                status, url, page = call("GET", "/swagger-ui.html")
                check("/swagger-ui.html opens the Swagger UI", status == 200 and "swagger-ui" in page.lower(),
                      "references/new-project.md step 2", "status %s at %s" % (status, url))
                status, _, body = call("POST", "/api/shop/product/search", {})
                check("POST /search with {} answers a page without signing in",
                      status == 200 and '"content"' in body, "references/new-project.md steps 2 and 3",
                      "status %s: %s" % (status, body[:160]))
                status, _, body = call("POST", "/api/shop/product", {"name": "Free", "price": 0})
                check("a price of 0 answers 400 'price: price must be positive', before sign-in",
                      status == 400 and "price must be positive" in body, "references/new-project.md step 4",
                      "status %s: %s" % (status, body[:160]))
                status, _, body = call("POST", "/api/shop/product", {"name": "Pen", "price": 1.5})
                check("creating a product without signing in answers 401 'Sign in to create Product'",
                      status == 401 and "Sign in to create Product" in body, "references/new-project.md step 3",
                      "status %s: %s" % (status, body[:160]))
        finally:
            app.terminate()
            try:
                app.wait(timeout=30)
            except subprocess.TimeoutExpired:
                app.kill()
            log.close()

    # --- the board recipe and the quick reference's sample, built and called as written ---------
    recipe = blocks_by_heading(RECIPE_BOARD)
    sample = blocks_by_heading(QUICK_REFERENCE)
    recipe_files = ["src/main/java/com/acme/board/BoardApplication.java",
                    "src/main/resources/blueprint/board/env.yml", "src/main/resources/blueprint/board/model/entity.yml"]
    check("recipe-board.md has its three files", sorted(recipe) == recipe_files,
          "references/recipe-board.md", "found: %s" % sorted(recipe))
