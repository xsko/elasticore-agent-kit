    dto = find(java, "ProductDTO.java")
    owned = find(java, "ProductService.java")
    if dto and owned:
        decisions = []
        for path in (dto, owned, schema, messages):
            rc_one, out_one, _ = hook("pre-edit", edit_payload("contract", path))
            try:
                decisions.append(json.loads(out_one)["hookSpecificOutput"]["permissionDecision"])
            except (ValueError, KeyError, TypeError):
                decisions.append("allow" if rc_one == 0 and not out_one.strip() else "error")
