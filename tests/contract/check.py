"""Checks, against real builds, the ElastiCORE behaviour this kit relies on.

The skill, the agents and the hooks assume a number of things about ElastiCORE:
how a generated file is marked, what each generator prints, which guides it
copies into a project, which tasks its Gradle plugin adds, what the new-project
template does in a browser. This builds the template from
references/new-project.md and the example from references/example-order.md
with the ElastiCORE release under test - the newest 3.x on Maven Central
unless ELASTICORE_VERSION names one - and a second project on the 2.x
generator, and fails, naming the assumption and where the kit states it, as
soon as one no longer holds.

A version ending in -SNAPSHOT is taken from the local Maven repository as well
(mavenLocal() before mavenCentral()). The contracts of references/recipe-library.md
need ElastiCORE 3.0.261021 or later; with an older one they are reported SKIP.

usage: python tests/contract/check.py [--gradle GRADLE] [--bash BASH] [--java JAVA] [--work DIR]
  GRADLE  the Gradle command, Gradle 8.14 or later (default: gradle on the PATH)
  BASH    the bash that runs the hook script (default: Git Bash on Windows, else bash on the PATH)
  JAVA    the java that runs the built application (default: JAVA_HOME's, else java on the PATH)
  DIR     an empty directory for the projects (default: a new temporary one, kept)
"""
