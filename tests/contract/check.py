"""Checks, against a real build, the ElastiCORE behaviour this kit relies on.

The skill, the agents and the hooks assume a few things about ElastiCORE: how a
generated file is marked, what the generator prints, which guides it copies into
a project, which tasks its Gradle plugin adds. This writes a small project,
builds it with the ElastiCORE release under test - the newest on Maven Central
unless ELASTICORE_VERSION names one - and fails, naming the assumption and where
the kit states it, as soon as one no longer holds.

usage: python tests/contract/check.py [--gradle GRADLE] [--bash BASH] [--work DIR]
  GRADLE  the Gradle command, Gradle 8.14 or later (default: gradle on the PATH)
  BASH    the bash that runs the hook script (default: bash on the PATH)
  DIR     an empty directory for the project (default: a new temporary one, kept)
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request

KIT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PROJECT = os.path.join(KIT, "tests", "contract", "project")
PLUGIN = os.path.join(KIT, "plugins", "elasticore")
SKILL = os.path.join(PLUGIN, "skills", "elasticore", "SKILL.md")
EXAMPLE = os.path.join(PLUGIN, "skills", "elasticore", "references", "example-order.md")
HOOK = os.path.join(PLUGIN, "hooks", "elasticore-hook.sh")
METADATA = "https://repo1.maven.org/maven2/io/elasticore/elasticore-base/maven-metadata.xml"

OWNED_LINE = "// Initially generated by ElastiCORE; no longer managed - do not remove this line."
SUMMARY = re.compile(r"=== elcore3: (\d+) written / (\d+) unchanged / (\d+) skipped / (\d+) failed ===")

results = []


def check(name, ok, where, detail=""):
    results.append((bool(ok), name, where, detail))
    if ok:
        print("PASS  " + name)
    else:
        print("FAIL  " + name + "\n      the kit relies on it in: " + where
              + ("\n      " + detail if detail else ""))
    return bool(ok)


def latest_version():
    request = urllib.request.Request(METADATA, headers={"User-Agent": "elasticore-agent-kit"})
    with urllib.request.urlopen(request, timeout=60) as response:
        text = response.read().decode("utf-8")
    found = re.search(r"<latest>([^<]+)</latest>", text) or re.search(r"<release>([^<]+)</release>", text)
    if not found:
        sys.exit("no version in " + METADATA)
    return found.group(1)


def example_files():
    """The YAML blocks of example-order.md, by the file name each heading gives."""
    with open(EXAMPLE, encoding="utf-8") as f:
        text = f.read()
    return dict(re.findall(r"^## `model/([\w.-]+\.yml)`\s*\n+```yaml\n(.*?)```", text, re.S | re.M))


def guides_named_in_skill():
    with open(SKILL, encoding="utf-8") as f:
        section = f.read().split("## 1.", 1)[1].split("## 2.", 1)[0]
    return sorted(set(re.findall(r"`(elasticore-[\w-]+\.md)`", section)))


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def find(root, name):
    for directory, _, files in os.walk(root):
        if name in files:
            return os.path.join(directory, name)
    return None


def kind(path):
    """The hook's classification, done here independently from the file itself."""
    text = read(path)
    if not text.startswith("//ecd:"):
        return "hand"
    if OWNED_LINE.split(";")[0] in text[:600]:
        return "owned"
    return "block" if "// !----------" in text else "managed"


def status_of(output, file_name):
    for line in output.splitlines():
        if file_name in line:
            found = re.search(r"\s(WROTE|UNCHANGED|SKIP\([^)]*\)|REGENERATED\([^)]*\)|ERROR.*)\s*$", line)
            if found:
                return found.group(1)
    return None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--gradle", default=os.environ.get("GRADLE", "gradle"))
    parser.add_argument("--bash", default=os.environ.get("HOOK_BASH") or shutil.which("bash") or "bash")
    parser.add_argument("--work")
    args = parser.parse_args()

    version = os.environ.get("ELASTICORE_VERSION") or latest_version()
    work = args.work or tempfile.mkdtemp(prefix="elasticore-contract-")
    project = os.path.join(work, "shop")
    print("ElastiCORE %s, project in %s" % (version, project))

    shutil.copytree(PROJECT, project)
    template = os.path.join(project, "build.gradle.template")
    write(os.path.join(project, "build.gradle"), read(template).replace("@ELASTICORE_VERSION@", version))
    os.remove(template)
    model = os.path.join(project, "src", "main", "resources", "blueprint", "shop", "model")
    example = example_files()
    check("example-order.md has the three model files", sorted(example) == ["dto.yml", "enum.yml", "order.yml"],
          "references/example-order.md", "found: %s" % sorted(example))
    for name, text in example.items():
        write(os.path.join(model, name), text)

    gradle = args.gradle.split()

    def run(*tasks):
        p = subprocess.run(gradle + list(tasks) + ["--console=plain"], cwd=project, capture_output=True,
                           text=True, encoding="utf-8", errors="replace")
        return p.returncode, re.sub(r"\x1b\[[0-9;]*m", "", p.stdout + p.stderr)

    data = os.path.join(work, "hook-data")

    def hook(event, payload):
        p = subprocess.run([args.bash, HOOK, event], input=json.dumps(payload, ensure_ascii=False),
                           capture_output=True, text=True, encoding="utf-8",
                           env=dict(os.environ, CLAUDE_PLUGIN_DATA=data))
        return p.returncode, p.stdout, p.stderr

    # --- the example generates and compiles ----------------------------------------
    rc, out = run("compileJava")
    write(os.path.join(work, "compileJava.log"), out)
    summary = SUMMARY.search(out)
    check("compileJava generates first and passes", rc == 0 and summary,
          "SKILL.md section 4 (compileJava regenerates first); references/example-order.md",
          "exit %d; see %s" % (rc, os.path.join(work, "compileJava.log")))
    check("the generator prints its summary line, with 0 failed", summary and summary.group(4) == "0",
          "SKILL.md section 5; skills/generate")
    check("the example has no DSL validation warning", "DSL validation warnings" not in out,
          "references/example-order.md")

    java = os.path.join(project, "src", "main", "java")
    blueprint = os.path.dirname(model).rsplit(os.sep, 1)[0]

    # --- the guides the skill sends the agent to ----------------------------------------
    missing = [g for g in guides_named_in_skill() if not os.path.isfile(os.path.join(blueprint, g))]
    check("every guide SKILL.md names is copied into blueprint/", not missing,
          "SKILL.md section 1", "missing: %s" % missing)

    # --- how files are marked ----------------------------------------------------------
    expected = {"ProductDTO.java": "managed", "ProductService.java": "owned",
                "PurchaseOrderBase.java": "managed", "PurchaseOrder.java": "owned"}
    for name, want in expected.items():
        path = find(java, name)
        got = kind(path) if path else "missing"
        check("%s is %s" % (name, want), got == want,
              "SKILL.md section 2; hooks/elasticore-hook.sh classify()", "found: %s" % got)
    owned = find(java, "ProductService.java")
    check("a developer-owned file carries the exact ownership line",
          owned and OWNED_LINE in read(owned)[:600], "SKILL.md section 2; agents/modeler.md, agents/reviewer.md")
    ids = [p for p in (find(java, "PurchaseOrderBase.java"), find(java, "OrderLine.java")) if p]
    check("@genid on string(36) generates IdUtils.newId(36)",
          ids and all("IdUtils.newId(36)" in read(p) for p in ids), "SKILL.md section 8")

    # --- the hook on files the generator really wrote ---------------------------------------
    dto = find(java, "ProductDTO.java")
    if dto and owned:
        rc_dto, out_dto, _ = hook("pre-edit", {"session_id": "contract", "tool_name": "Edit",
                                               "tool_input": {"file_path": dto, "old_string": "a", "new_string": "b"}})
        rc_owned, out_owned, _ = hook("pre-edit", {"session_id": "contract", "tool_name": "Edit",
                                                   "tool_input": {"file_path": owned, "old_string": "a", "new_string": "b"}})
        try:
            decision = json.loads(out_dto)["hookSpecificOutput"]["permissionDecision"]
        except (ValueError, KeyError, TypeError):
            decision = None
        check("the hook refuses an edit to a generated file and allows the owned one",
              rc_dto == 0 and decision == "deny" and rc_owned == 0 and not out_owned.strip(),
              "hooks/elasticore-hook.sh pre-edit",
              "generated: exit %d, %s; owned: exit %d, %s" % (rc_dto, out_dto.strip()[:160], rc_owned, out_owned.strip()[:80]))

    # --- a hand edit to a generated file, and how it is undone -----------------------------
    if dto:
        with open(dto, "a", encoding="utf-8", newline="\n") as f:
            f.write("// edited by hand\n")
        rc, out = run("elcore3")
        check("a hand-edited generated file is reported SKIP(user-modified; -Pforce to overwrite)",
              status_of(out, "ProductDTO.java") == "SKIP(user-modified; -Pforce to overwrite)",
              "SKILL.md sections 2 and 5; hooks/elasticore-hook.sh post-bash",
              "status: %s" % status_of(out, "ProductDTO.java"))
        payload = {"session_id": "contract", "tool_name": "Bash", "tool_input": {"command": "./gradlew elcore3"},
                   "tool_response": {"stdout": out, "stderr": "", "interrupted": False, "isImage": False}}
        _, note, _ = hook("post-bash", payload)
        check("the hook recognises that report in real output", "edited by hand" in note,
              "hooks/elasticore-hook.sh post-bash", "hook said: %s" % note.strip()[:200])
        os.remove(dto)
        rc, out = run("elcore3")
        check("deleting a generated file and generating again restores it",
              status_of(out, "ProductDTO.java") == "WROTE" and kind(dto) == "managed", "SKILL.md section 5",
              "status: %s" % status_of(out, "ProductDTO.java"))

    # --- what a DSL mistake looks like ------------------------------------------------------
    entity = os.path.join(model, "entity.yml")
    original = read(entity)
    write(entity, original + "      weight:    kilogramz\n")
    rc, out = run("elcore3")
    check("an unknown type is listed under 'DSL validation warnings:' and the build still passes",
          rc == 0 and "DSL validation warnings:" in out and "unresolved type 'kilogramz'" in out,
          "SKILL.md sections 4 and 5; agents; hooks/elasticore-hook.sh post-bash")
    payload = {"session_id": "contract", "tool_name": "Bash", "tool_input": {"command": "./gradlew elcore3"},
               "tool_response": {"stdout": out, "stderr": "", "interrupted": False, "isImage": False}}
    _, note, _ = hook("post-bash", payload)
    check("the hook recognises the warnings in real output", "DSL validation warnings" in note,
          "hooks/elasticore-hook.sh post-bash", "hook said: %s" % note.strip()[:200])
    write(entity, original)
    run("elcore3")

    # --- the tasks the skill names ------------------------------------------------------------
    rc, out = run("tasks", "--all")
    names = set(re.findall(r"^(\S+) - ", out, re.M))
    missing = [t for t in ("elcore", "elcore3", "elcore3ts") if t not in names]
    check("the Gradle plugin adds elcore, elcore3 and elcore3ts", rc == 0 and not missing,
          "SKILL.md section 4", "missing: %s" % missing)

    failed = [r for r in results if not r[0]]
    summary_file = os.environ.get("GITHUB_STEP_SUMMARY")
    if summary_file:
        with open(summary_file, "a", encoding="utf-8") as f:
            f.write("### ElastiCORE %s: %d of %d contracts hold\n\n" % (version, len(results) - len(failed), len(results)))
            for ok, name, where, detail in results:
                f.write("- %s %s%s\n" % ("PASS" if ok else "**FAIL**", name, "" if ok else " - " + where))
    print("\nElastiCORE %s: %d of %d contracts hold" % (version, len(results) - len(failed), len(results)))
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
