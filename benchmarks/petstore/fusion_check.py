"""How hand-written code sits on the generated code of an ElastiCORE project.

usage: python fusion_check.py PROJECT_DIR [--force]
Prints: every source file under src/ by owner (generated / owned-generated / hand-written) with its
non-blank line count; then runs `gradlew.bat elcore3` (no force) and reports the generator's summary
and every SKIP(user-modified ...) line - a generated file edited by hand, which the DSL no longer
drives. With --force, copies the project (without build/.gradle) to a temp dir, runs
`gradlew.bat elcore3 -Pforce` there, then `gradlew.bat build -x test`, and says whether the hand code
still compiles once the generated files are restored from the DSL.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile

project = os.path.abspath(sys.argv[1])
force = "--force" in sys.argv
sys.stdout.reconfigure(encoding="utf-8")
SRC_EXT = (".java", ".kt", ".ts", ".yml", ".yaml", ".properties", ".html", ".js", ".sql", ".xml")


def classify(path):
    try:
        with open(path, encoding="utf-8", errors="replace") as f:
            text = f.read()
    except OSError:
        return "unreadable", 0
    lines = sum(1 for l in text.splitlines() if l.strip())
    first = text.split("\n", 1)[0]
    if first.startswith("//ecd:") or first.startswith("# ecd:") or first.startswith("<!--ecd:"):
        if "Initially generated by ElastiCORE" in text:
            return "owned-generated", lines
        if "// !----------" in text:
            return "generated+block", lines
        return "generated", lines
    if "Generated by ElastiCORE" in text[:300] or os.path.basename(path).startswith("elasticore-"):
        return "generated", lines
    return "hand-written", lines


rows = []
for root, dirs, files in os.walk(os.path.join(project, "src")):
    dirs[:] = [d for d in dirs if d not in ("build", "node_modules")]
    for name in files:
        if name.endswith(SRC_EXT):
            p = os.path.join(root, name)
            kind, n = classify(p)
            rows.append((kind, n, os.path.relpath(p, project).replace("\\", "/")))

totals = {}
for kind, n, rel in sorted(rows):
    totals.setdefault(kind, [0, 0])
    totals[kind][0] += 1
    totals[kind][1] += n
print("== files by owner")
for kind in sorted(totals):
    print("%-16s %4d files %6d non-blank lines" % (kind, totals[kind][0], totals[kind][1]))
print("== hand-written and owned files")
for kind, n, rel in sorted(rows):
    if kind in ("hand-written", "owned-generated", "generated+block"):
        print("%-16s %5d  %s" % (kind, n, rel))


def gradle(cwd, *args):
    env = dict(os.environ, TEMP=os.path.join(cwd, "tmp"), TMP=os.path.join(cwd, "tmp"))
    os.makedirs(env["TEMP"], exist_ok=True)
    r = subprocess.run([os.path.join(cwd, "gradlew.bat")] + list(args) + ["--console=plain", "--no-daemon", "-q"],
                       cwd=cwd, env=env, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return r.returncode, r.stdout + r.stderr


if "--inventory" in sys.argv:
    sys.exit(0)

# Every Gradle step runs on a copy: the project may be in use (a grader building it), and the
# generator's state is in the files themselves (the //ecd: hash line), so a copy answers the same.
tmp = tempfile.mkdtemp(prefix="fusion-")
copy = os.path.join(tmp, "project")
shutil.copytree(project, copy, ignore=shutil.ignore_patterns("build", ".gradle", "node_modules", "tmp", ".kotlin"))
print("copy:", copy)
print("== elcore3 (no force) on the copy")
code, out = gradle(copy, "elcore3")
summary = [l for l in out.splitlines() if "=== elcore" in l or "DSL validation warnings" in l or "LOAD ERROR" in l]
skips = [l.strip() for l in out.splitlines() if "SKIP(user-modified" in l]
warns = [l.strip() for l in out.splitlines() if re.match(r"\s*\[\w+\] \w+", l) and "unresolved" in l or "warning" in l.lower() and "[" in l]
print("exit", code)
for l in summary:
    print(l.strip())
print("SKIP(user-modified): %d" % len(skips))
for l in skips:
    print("  " + l)
if code != 0:
    print(out[-3000:])

if force:
    print("== -Pforce regeneration on the copy, then build -x test")
    code, out = gradle(copy, "elcore3", "-Pforce")
    print("elcore3 -Pforce exit", code)
    for l in out.splitlines():
        if "=== elcore" in l or "ERROR" in l:
            print(l.strip())
    code, out = gradle(copy, "build", "-x", "test")
    print("build -x test exit", code)
    if code != 0:
        errs = [l for l in out.splitlines() if "error:" in l or "e: " in l or "FAILED" in l]
        for l in errs[:40]:
            print("  " + l.strip())
    print("copy:", copy)
